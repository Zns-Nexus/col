/**
 * The verified component index — the data behind searching by component name.
 *
 * Separate from `data/libraries.ts` because this grows on a different
 * cadence: libraries arrive rarely, but a single component collection can
 * document hundreds of components at once. Each entry is keyed by the owning
 * library's `slug`.
 *
 * Guidelines:
 * - `name` must be the component's official name as the library documents it.
 * - `url` must be that component's own documentation page, on the library's
 *   own domain, not a marketing or setup page.
 * - `aliases` are optional terms people genuinely search for. Add them only
 *   when the official name would not match how someone describes the
 *   component, and never pad them with synonyms.
 * - Coverage is partial and grows by contribution. A missing entry means "not
 *   yet verified", never "this library does not have it". Do not infer a
 *   component from a library's generic tags.
 *
 * Every `url` below was taken from the library's own published component
 * index or documentation and checked to resolve. `lib/directory.test.mjs`
 * enforces that they stay on the library's domain and stay unique.
 */

/** A single named component a library documents, used for component search. */
export interface LibraryComponent {
  /** The component's official name, spelled as the library documents it. */
  name: string;
  /** Search terms people actually type that the official name does not cover. */
  aliases?: string[];
  /** Canonical documentation page for this exact component. */
  url: string;
  /** Exact command that installs this component, when the library documents one. */
  install?: string;
  /** npm packages this component installs, as its registry records them. */
  dependencies?: string[];
  /** Registry components this one pulls in, by registry name. */
  registryDependencies?: string[];
  /** What kind of thing this is: a full pattern, a primitive, a visual effect, or a layout. */
  kind?: ComponentKind;
  /** One line on what the component is for. */
  summary?: string;
  /** The primitive or package this component wraps, when it wraps one. */
  builtOn?: string;
  /** Shared concept id linking the same idea across libraries. */
  concept?: string;
  /** ISO date Col last verified this record's source page. */
  verifiedAt?: string;
  /** Alternative documentation pages the library keeps for the same component. */
  variants?: Record<string, string>;
}

/** What kind of thing a component is, so a visual effect never poses as a search UI. */
export type ComponentKind = "full-pattern" | "primitive" | "visual-effect" | "layout";

